#!/usr/bin/env bash
# Regenerates THIRD_PARTY_LICENSES.md from the modules linked into the server binary.
# Run after any dependency change and commit the result. Needs Go and a populated module cache.
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
out="$root/THIRD_PARTY_LICENSES.md"
cd "$root"
{
  echo "# Third-party licenses"
  echo
  echo "The server binary links the Go modules below. Each module's license text follows."
  echo "Generated by scripts/gen-licenses.sh; do not edit by hand."
  go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}|{{.Dir}}{{end}}{{end}}' ./cmd/slack-mcp-server | sort -u | while IFS='|' read -r label dir; do
    echo
    echo "## $label"
    echo
    found=0
    for f in "$dir"/LICENSE* "$dir"/COPYING* "$dir"/NOTICE*; do
      [ -f "$f" ] || continue
      found=1
      echo '```text'
      cat "$f"
      echo
      echo '```'
    done
    [ "$found" = 1 ] || echo "(no license file found in the module; see its repository)"
  done
} > "$out"
echo "wrote $out"
